import { calendarHubApi as companyCalendarApi } from './calendarHubApi';
import { companyRequest } from './companyAuth';
let initialLoading = true;
import { appraisalApi } from './appraisalApi';
﻿import { workflowApi } from './workflowApi';
let notifications = [];
let connected = false;
let timer = null;
let inFlight = false;
let sessionToken = null;
const listeners = new Set();
const token = () => localStorage.getItem('pulse_hrms_token');
const notify = () => listeners.forEach(listener => listener(notifications,connected,initialLoading));
async function refresh() {
  const current = token();
  if (sessionToken !== current) { sessionToken = current; notifications = []; connected = false; initialLoading = true; notify(); }
  if (!current) { initialLoading = false; notify(); return; }
  if (inFlight) return;
  inFlight = true;
  try {
    const results = await Promise.allSettled([workflowApi.notifications(), appraisalApi.notifications(), companyCalendarApi.reminders(), companyRequest('/documents/assistant/alerts',{token:current})]);
    if (results.every(result => result.status === 'rejected')) throw new Error('Notifications unavailable.');
    const result = results.flatMap(item => item.status === 'fulfilled' ? item.value : []).sort((a,b)=>new Date(b.timestamp || b.created_at)-new Date(a.timestamp || a.created_at));
    if (current !== token()) return;
    notifications = result; connected = true; initialLoading = false; notify();
  } catch {
    if (current === token()) { connected = false; initialLoading = false; notify(); }
  } finally { inFlight = false; }
}
export function connectRealtimeNotifications() { refresh(); }
export function subscribeNotifications(callback) {
  if (sessionToken !== token()) { sessionToken = token(); notifications = []; connected = false; initialLoading = true; }
  listeners.add(callback); callback(notifications,connected,initialLoading); refresh();
  if (!timer) timer = setInterval(() => { if (!document.hidden) refresh(); },60000);
  return () => { listeners.delete(callback); if (!listeners.size) { clearInterval(timer); timer = null; notifications = []; connected = false; initialLoading = true; } };
}
export async function markNotificationRead(id) { if(String(id).startsWith('calendar:')) await companyCalendarApi.readReminders(id); else if(String(id).startsWith('doc-alert:')) await companyRequest('/documents/assistant/alerts/read',{token:token(),method:'POST',body:JSON.stringify({id})}); else if(String(id).startsWith('appraisal:')) await appraisalApi.read(id); else await workflowApi.read(id); await refresh(); }
export async function markAllNotificationsRead() { const tasks=[]; if(notifications.some(n=>String(n.id).startsWith('calendar:')))tasks.push(companyCalendarApi.readReminders()); if(notifications.some(n=>String(n.id).startsWith('doc-alert:')))tasks.push(companyRequest('/documents/assistant/alerts/read',{token:token(),method:'POST',body:'{}'})); if(notifications.some(n=>!String(n.id).startsWith('calendar:')&&!String(n.id).startsWith('appraisal:')&&!String(n.id).startsWith('doc-alert:')))tasks.push(workflowApi.read());if(notifications.some(n=>String(n.id).startsWith('appraisal:')))tasks.push(appraisalApi.read());await Promise.all(tasks); await refresh(); }
export async function approveNotificationAction(id) {
  const notification = notifications.find(item => item.id === id);
  if (!notification?.canApprove || !notification.requestId) throw new Error('You are not the assigned approver for this request.');
  const result = await workflowApi.decide(notification.requestId,'Approved','');
  await refresh(); return result;
}
