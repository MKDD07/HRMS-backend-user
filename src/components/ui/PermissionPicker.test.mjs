import assert from 'node:assert/strict';
import { buildSync } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import Module from 'node:module';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const filename = fileURLToPath(new URL('./PermissionPicker.jsx', import.meta.url));
const compiled = buildSync({ entryPoints: [filename], bundle: true, packages: 'external', write: false, format: 'cjs', platform: 'node', loader: { '.scss': 'empty' } });
const loaded = new Module(filename);
loaded.paths = Module._nodeModulePaths(path.dirname(filename));
loaded._compile(compiled.outputFiles[0].text, filename);
const { PermissionPicker } = loaded.exports;
const options = [['employees', 'Employee directory'], ['payroll', 'Payroll'], ['reports', 'Reports']];
const render = props => renderToStaticMarkup(React.createElement(PermissionPicker, { options, value: ['employees'], onChange() {}, ...props }));
const editable = render({});
assert.equal((editable.match(/type="checkbox"/g) || []).length, 3);
assert.equal((editable.match(/checked=""/g) || []).length, 1);
assert.match(editable, /1 of 3 selected/);
assert.match(editable, /Search allowed pages/);
assert.match(editable, /Selected only/);
assert.match(editable, /aria-pressed="false"/);
assert.doesNotMatch(editable, /Select all|Grant all/);
assert.equal((render({ disabled: true }).match(/disabled=""/g) || []).length, 5);
assert.equal((render({ onChange: undefined }).match(/type="checkbox"[^>]*disabled=""/g) || []).length, 3);
assert.match(render({ options: [], value: [] }), /No pages match this search/);
assert.match(render({ value: ['employees', 'unknown'] }), /1 of 3 selected/);
const multiple = renderToStaticMarkup(React.createElement('div', null, React.createElement(PermissionPicker, { options, value: [] }), React.createElement(PermissionPicker, { options, value: [] })));
const titles = [...multiple.matchAll(/<h3 id="([^"]+)"/g)].map(match => match[1]);
assert.equal(new Set(titles).size, 2);
console.log('Permission picker checks passed: explicit selection, disabled controls, search, counts, empty state, and unique labels.');
