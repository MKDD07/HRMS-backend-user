export function documentReview(metadata = {}) {
  const draft = metadata.draft === true || metadata.review_status === 'draft';
  const origin = ['human','ai'].includes(metadata.origin) ? metadata.origin : metadata.category === 'AI Draft Letters' || /Generated by Aster AI/i.test(metadata.description || '') ? 'ai' : 'human';
  return { draft, origin, review_status: draft ? 'draft' : 'approved' };
}
