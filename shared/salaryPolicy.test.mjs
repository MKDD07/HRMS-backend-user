import assert from 'node:assert/strict';
import { structureDefaults } from './indiaSalaryStructure.mjs';
import { calculatePolicySalary, configuredSalaryPolicy, validateSalaryComponents } from './salaryPolicy.mjs';
import { normalizeSalary } from '../src/lib/payslipModel.js';
const policy=structureDefaults(2026,9);
// Regression: entering 45,000 basic must derive gross and HRA, not leave PF at zero.
const basic=45000,gross=basic*100/policy.basicPercent;
const calculated=calculatePolicySalary({},policy,gross);
assert.equal(calculated.basic,45000);
assert.equal(calculated.hra,18000);
assert.equal(calculated.special_allowance,27000);
assert.equal(calculated.monthly_gross,90000);
assert.equal(calculated.pf_deduction,3000);
assert.equal(calculated.gratuity_provision,2163.46);
const rows=[{name:'Shift allowance',type:'earning',mode:'percent',basis:'basic',value:10},{name:'Meal deduction',type:'deduction',mode:'fixed',basis:'gross',value:500}];
const custom=calculatePolicySalary({},policy,90000,rows);
assert.equal(custom.monthly_gross,94500);
assert.equal(custom.custom_earnings.find(r=>r.name==='Shift allowance').amount,4500);
assert.equal(custom.monthly_net,91000);
const changed=calculatePolicySalary(custom,policy,100000,rows);
assert.equal(changed.custom_earnings.filter(r=>r.name==='Shift allowance').length,1);
assert.equal(changed.custom_earnings.find(r=>r.name==='Shift allowance').amount,5000);
const tampered={...changed,custom_earnings:[{name:'Shift allowance',amount:1}]};
assert.equal(normalizeSalary(tampered).custom_earnings.find(r=>r.name==='Shift allowance').amount,5000);
assert.throws(()=>validateSalaryComponents([{...rows[0],name:'ESI employee'}]),/reserved/);
assert.throws(()=>validateSalaryComponents([rows[0],rows[0]]),/unique/);
const configured=configuredSalaryPolicy({assignments:[{id:'EMP',group_id:'G'}],groups:[{id:'G',name:'Engineering',salary_structure:{...policy,hraPercent:50},salary_components:rows}]},'EMP',2026,9);
assert.equal(configured.policy.hraPercent,50);
assert.equal(configured.components.length,2);
console.log('Salary policy tests passed: basic input, gross, HRA, PF, gratuity, assignment and component recalculation.');
