import assert from 'node:assert/strict';
import { shiftTimingError } from './shiftTiming.mjs';
import { dashboardConfiguration } from '../worker/dashboardAdmin.mjs';
const base = {id:'day', name:'Day', startTime:'09:00', endTime:'18:00', breakDurationMins:30, gracePeriodMins:10, workingDays:['Mon'], status:'Active', isDefault:false};
assert.equal(shiftTimingError(base), '');
const configured = {...base, breakStartTime:'13:00', breakEndTime:'13:30', shortLeaveEnabled:true, earlyInEnabled:true, earlyInTime:'08:30', earlyOutEnabled:true, earlyOutTime:'17:00'};
assert.equal(shiftTimingError(configured), '');
assert.equal(shiftTimingError({...configured, startTime:'22:00', endTime:'06:00', breakStartTime:'01:00', breakEndTime:'01:30'}), '');
assert.match(shiftTimingError({...configured, breakEndTime:''}), /both break/);
assert.match(shiftTimingError({...configured, breakEndTime:'14:00'}), /duration/);
assert.match(shiftTimingError({...configured, breakStartTime:'19:00', breakEndTime:'19:30'}), /within/);
assert.match(shiftTimingError({...configured, earlyInTime:''}), /early-in/);
assert.match(shiftTimingError({...configured, earlyInEnabled:false, earlyOutEnabled:false}), /Enable/);
assert.equal(shiftTimingError({...configured, shortLeaveEnabled:false, earlyInTime:''}), '');
let stored;
const db={prepare(sql){ return {bind(...params){return {async first(){if(sql.startsWith('SELECT')) return stored ? {revision:1,payload:stored} : null; stored=params[2]; return {revision:1};}};}};}};
const actor={role:'company_admin',company_id:'company'};
const saved=await dashboardConfiguration({db,actor,section:'shifts',method:'POST',body:{revision:0,value:[configured]}});
assert.deepEqual(saved.value[0], configured);
const loaded=await dashboardConfiguration({db,actor,section:'shifts',method:'GET'});
assert.deepEqual(loaded.value[0], configured);
await assert.rejects(dashboardConfiguration({db,actor,section:'shifts',method:'POST',body:{revision:1,value:[{...configured,earlyOutTime:'invalid'}]}}), /early-out/);
console.log('Shift timing validation and configuration persistence checks passed');
