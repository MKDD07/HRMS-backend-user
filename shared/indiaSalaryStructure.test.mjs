import assert from 'node:assert/strict';
import { applyIndiaBenefits, calculateIndiaStructure, structureDefaults } from './indiaSalaryStructure.mjs';
import { normalizeSalary } from '../src/lib/payslipModel.js';
const defaults=structureDefaults(2026,9);
assert.equal(defaults.pfCeiling,25000);
assert.equal(structureDefaults(2026,7).pfCeiling,15000);
const salary=calculateIndiaStructure({...defaults,gross:50000});
assert.equal(salary.basic,25000);
assert.equal(salary.hra,10000);
assert.equal(salary.special_allowance,15000);
assert.equal(salary.pf_deduction,3000);
assert.equal(salary.monthly_net,47000);
assert.equal(salary.gratuity_provision,1201.92);
assert.equal(salary.annual_ctc,650423.04);
assert.equal(normalizeSalary(salary).annual_ctc,salary.annual_ctc);
assert.deepEqual(normalizeSalary(salary).india_structure,salary.india_structure);
const esi=calculateIndiaStructure({...defaults,gross:20000,esiCovered:true});
assert.equal(esi.total_deductions,1350);
assert.equal(esi.employer_esi,650);
assert.equal(calculateIndiaStructure({...defaults,gross:0}).monthly_net,0);
assert.throws(()=>calculateIndiaStructure({...defaults,gross:50000,basicPercent:90,hraPercent:50}),/exceed/);
assert.throws(()=>calculateIndiaStructure({...defaults,gross:50000,tds:60000}),/exceed/);
assert.throws(()=>calculateIndiaStructure({...defaults,basicPercent:-1}),/valid/);
const edited=applyIndiaBenefits({...salary,basic:20000,special_allowance:20000});
assert.equal(edited.pf_deduction,2400);
assert.equal(edited.gratuity_provision,961.54);
assert.equal(edited.monthly_gross,50000);
assert.equal(normalizeSalary(edited).employer_pf,2400);
const exempt=applyIndiaBenefits({...esi,india_structure:{...esi.india_structure,esiEmployeeExempt:true}});
assert.ok(!exempt.custom_deductions.some(r=>r.name==='ESI employee'));
assert.equal(exempt.employer_esi,650);
assert.deepEqual(applyIndiaBenefits(applyIndiaBenefits(esi)),applyIndiaBenefits(esi));
console.log('Indian salary structure checks passed');
