import { test } from 'node:test';
import assert from 'node:assert/strict';
import { documentReview } from './documentReview.mjs';
test('human and AI drafts stay separate until approved', () => {
  assert.deepEqual(documentReview({ draft: true, origin: 'human' }), { draft: true, origin: 'human', review_status: 'draft' });
  assert.deepEqual(documentReview({ draft: true, origin: 'ai' }), { draft: true, origin: 'ai', review_status: 'draft' });
  assert.deepEqual(documentReview({ draft: false, origin: 'ai', review_status: 'approved' }), { draft: false, origin: 'ai', review_status: 'approved' });
});
test('existing AI drafts are identified and existing published policies remain available', () => {
  assert.equal(documentReview({ draft: true, category: 'AI Draft Letters' }).origin, 'ai');
  assert.equal(documentReview({ draft: true, description: 'Generated by Aster AI' }).origin, 'ai');
  assert.equal(documentReview({}).review_status, 'approved');
});
