const fs = require('node:fs');
const path = require('node:path');
const sass = require('sass');
const postcss = require('postcss');
const { SourceMapConsumer } = require('source-map-js');
const target = path.resolve('src/pages/dashboard/DashboardPage.scss');
const result = sass.compile(target, { sourceMap: true, style: 'expanded' });
const map = new SourceMapConsumer(result.sourceMap);
const root = postcss.parse(result.css);
const groups = new Map();
const duplicateProperties = [];
function origin(node) {
  return map.originalPositionFor({ line: node.source.start.line, column: node.source.start.column - 1 });
}
root.walkRules(rule => {
  const location = origin(rule);
  if (!location.source?.endsWith('/DashboardPage.scss')) return;
  const parents = [];
  for (let parent = rule.parent; parent && parent.type !== 'root'; parent = parent.parent) {
    if (parent.type === 'atrule') parents.unshift(`@${parent.name} ${parent.params}`);
  }
  const context = parents.join(' > ') || 'Base';
  const declarations = rule.nodes.filter(node => node.type === 'decl');
  const seen = new Map();
  for (const decl of declarations) {
    const property = decl.prop.startsWith('--') ? decl.prop : decl.prop.toLowerCase();
    if (seen.has(property)) duplicateProperties.push({ selector: rule.selector, context, line: origin(decl).line, property, previous: seen.get(property), value: decl.value });
    seen.set(property, decl.value);
  }
  for (const selector of rule.selectors) {
    const key = `${context}\n${selector}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push({ line: location.line, declarations: declarations.map(d => ({ property: d.prop, value: d.value + (d.important ? ' !important' : '') })) });
  }
});
const repeated = [...groups].filter(([, rules]) => new Set(rules.map(r => r.line)).size > 1);
let identical = 0, conflicting = 0;
const sections = repeated.map(([key, rules]) => {
  const [context, ...selectorParts] = key.split('\n');
  const selector = selectorParts.join('\n');
  const properties = new Map();
  for (const rule of rules) for (const d of rule.declarations) {
    if (!properties.has(d.property)) properties.set(d.property, []);
    properties.get(d.property).push({ line: rule.line, value: d.value });
  }
  const overlaps = [...properties].filter(([, entries]) => new Set(entries.map(e => e.line)).size > 1);
  const details = overlaps.map(([property, entries]) => {
    const same = new Set(entries.map(e => e.value)).size === 1;
    if (same) identical++; else conflicting++;
    return `| ${property} | ${same ? 'Repeated value' : 'Override / conflict'} | ${entries.map(e => `L${e.line}: \`${e.value}\``).join('<br>')} |`;
  });
  return `### \`${selector}\`\n\nContext: ${context}. Source lines: ${[...new Set(rules.map(r => r.line))].join(', ')}.\n\n${details.length ? '| Property | Finding | Values in source order |\n| --- | --- | --- |\n' + details.join('\n') : 'Selector is split across blocks; no identical property names overlap.'}`;
});
const crossContexts = new Map();
for (const [key] of groups) {
  const [context, ...parts] = key.split('\n'); const selector = parts.join('\n');
  if (!crossContexts.has(selector)) crossContexts.set(selector, new Set());
  crossContexts.get(selector).add(context);
}
const responsive = [...crossContexts].filter(([, contexts]) => contexts.size > 1);
const report = `# Dashboard stylesheet duplicate audit\n\nSource: \`src/pages/dashboard/DashboardPage.scss\`. Generated by \`node scripts/auditDashboardScss.cjs\`.\n\n## Findings\n\n- ${repeated.length} repeated selector/context groups.\n- ${identical} overlapping properties repeat the same compiled value.\n- ${conflicting} overlapping properties have different compiled values.\n- ${duplicateProperties.length} duplicate property declarations inside individual compiled rules.\n- ${responsive.length} selectors also occur in different at-rule contexts; these are listed separately and are not automatically duplicates.\n\nThis is an audit, not an automatic deletion tool. Sass is compiled and source-mapped back to this file; imports are excluded. Grouped selectors are expanded, so one authored block can produce multiple findings. Later declarations may be deliberate overrides. Shorthand/longhand interactions and overlaps between different selectors still require manual review. No stylesheet changes were made by this audit.\n\n## Repeated selectors in the same context\n\n${sections.join('\n\n')}\n\n## Duplicate properties within a rule\n\n${duplicateProperties.length ? duplicateProperties.map(d => `- L${d.line}, \`${d.selector}\` (${d.context}): \`${d.property}\` repeats as \`${d.previous}\` then \`${d.value}\`.`).join('\n') : 'None found.'}\n\n## Selectors across different contexts\n\n${responsive.map(([selector, contexts]) => `- \`${selector}\`: ${[...contexts].join('; ')}.`).join('\n')}\n`;
fs.writeFileSync('DASHBOARD_SCSS_AUDIT.md', report);
console.log(JSON.stringify({ repeatedSelectorGroups: repeated.length, repeatedPropertyValues: identical, conflictingPropertyValues: conflicting, duplicatePropertiesWithinRules: duplicateProperties.length, differentContexts: responsive.length }, null, 2));
console.log('Report: DASHBOARD_SCSS_AUDIT.md');
