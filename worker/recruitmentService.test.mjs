import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { readFileSync } from 'node:fs';
import { talentHandle } from './talent.mjs';
import { RECRUITMENT_TRANSITIONS, assertRecruitmentTransition } from '../shared/recruitmentModel.mjs';
for (const [collection,machine] of Object.entries(RECRUITMENT_TRANSITIONS)) for (const from of Object.keys(machine)) for (const to of Object.keys(machine)) {
  if (from === to || machine[from].includes(to)) assert.doesNotThrow(() => assertRecruitmentTransition(collection,from,to));
  else assert.throws(() => assertRecruitmentTransition(collection,from,to), error => error.status === 409);
}
const sqlite = new DatabaseSync(':memory:');
sqlite.exec("PRAGMA foreign_keys=ON; CREATE TABLE companies(company_id TEXT PRIMARY KEY); INSERT INTO companies VALUES('a'),('b'); CREATE TABLE employees(company_id TEXT,user_id TEXT);");
for (const file of ['0009_talent_operations.sql','0014_talent_recruitment_audit.sql']) sqlite.exec(readFileSync(new URL('../migrations/hrms/'+file,import.meta.url),'utf8'));
const prepare = (sql,params=[]) => ({ bind: (...values) => prepare(sql,values), first: async () => sqlite.prepare(sql).get(...params), all: async () => ({results:sqlite.prepare(sql).all(...params)}), run: async () => sqlite.prepare(sql).run(...params) });
const db = { prepare, async batch(statements) { sqlite.exec('BEGIN'); try { const result=[]; for(const statement of statements) result.push(await statement.run()); sqlite.exec('COMMIT'); return result; } catch(error) { sqlite.exec('ROLLBACK'); throw error; } } };
const actor = {company_id:'a',user_id:'admin-a',role:'company_admin'};
const save = (collection,body,as=actor) => talentHandle({db,actor:as,path:'/api/v1/talent/'+collection+(body.id?'/'+body.id:''),method:'POST',body,url:new URL('https://test')});
const reject = (promise,status) => assert.rejects(promise,error => error.status === status);
try {
  const input = {title:'Engineer',department:'Engineering',positions:2,employment_type:'Full-time',status:'Draft',justification:'Expand the platform team.'};
  await reject(save('requisitions',{...input,status:'Approved'}),409);
  const draft = await save('requisitions',input);
  const pending = await save('requisitions',{...draft,status:'Pending approval'});
  await reject(save('requisitions',{...pending,status:'Approved'}, {...actor,user_id:'recruiter',original_role:'employee'}),403);
  await reject(save('requisitions',{...pending,status:'Approved',positions:3}),409);
  await reject(save('requisitions',{...pending,status:'Rejected',rejection_reason:''}),400);
  const approved = await save('requisitions',{...pending,status:'Approved'});
  assert.equal(approved.approved_by,'admin-a'); assert.equal(approved.requested_by,'admin-a');
  assert.equal('last_change_id' in approved,false);
  await reject(save('requisitions',{...pending,status:'Cancelled'}),409);
  const job = await save('jobs',{title:'Engineer',department:'Engineering',positions:2,status:'Draft',description:'Build APIs.',requisition_id:approved.id});
  await reject(save('jobs',{...job,status:'Open'}, {...actor,company_id:'b'}),404);
  await reject(save('jobs',{...job,status:'Open',description:''}),400);
  await reject(save('jobs',{...job,status:'Open',positions:3}),400);
  const open = await save('jobs',{...job,status:'Open'});
  assert.equal(open.status,'Open');
  const held = await save('jobs',{...open,status:'On hold'});
  assert.equal((await save('jobs',{...held,status:'Open'})).status,'Open');
  assert.equal(sqlite.prepare('SELECT count(*) AS n FROM talent_audit').get().n,7);
  assert.equal(sqlite.prepare('SELECT count(*) AS n FROM talent_domain_events').get().n,7);
  const auditRead = (as,id) => talentHandle({db,actor:as,path:`/api/v1/talent/requisitions/${id}/audit`,method:'GET',url:new URL('https://test')});
  assert.equal((await auditRead(actor,approved.id)).length,3);
  await reject(auditRead({...actor,company_id:'b'},approved.id),404);
  sqlite.exec("INSERT INTO employees VALUES('a','interviewer-a'),('a','interviewer-two'),('b','interviewer-b');");
  const candidate = await save('candidates',{title:'Jane Candidate',email:'JANE@example.com',job_id:open.id,status:'Applied',source:'Direct'});
  assert.equal(candidate.email,'jane@example.com');
  await reject(save('candidates',{title:'Duplicate',email:'jane@example.com',job_id:open.id,status:'Applied'}),409);
  await reject(save('candidates',{...candidate,status:'Hired'}),409);
  await reject(save('candidates',{...candidate,status:'Rejected',rejection_reason:''}),400);
  const interviewing = await save('candidates',{...candidate,status:'Interview'});
  await reject(save('candidates',{...interviewing,status:'Offered'}),409);
  const interviewInput = {title:'Technical interview',candidate_id:candidate.id,interviewer_id:'interviewer-a',date:'2030-11-01',start_time:'10:00',end_time:'11:00',mode:'Video',status:'Scheduled'};
  const interview = await save('interviews',interviewInput);
  await reject(save('interviews',{...interviewInput,start_time:'10:30',end_time:'11:30'}),409);
  await reject(save('interviews',{...interviewInput,start_time:'09:30',end_time:'10:30'}),409);
  await reject(save('interviews',{...interviewInput,start_time:'09:00',end_time:'12:00'}),409);
  const adjacent = await save('interviews',{...interviewInput,start_time:'11:00',end_time:'12:00'});
  await save('interviews',{...interviewInput,interviewer_id:'interviewer-two'});
  await reject(save('interviews',{...interviewInput,interviewer_id:'interviewer-b'}),400);
  await reject(save('interviews',{...interviewInput,start_time:'24:00'}),400);
  await reject(save('interviews',{...interviewInput,end_time:'09:00'}),400);
  await reject(save('interviews',{...interview,status:'Completed',outcome:''}),400);
  await reject(save('interviews',{...interview,title:'Cross company'},{...actor,company_id:'b'}),404);
  const offer = await save('offers',{title:'Jane offer',candidate_id:candidate.id,joining_date:'2030-12-01',valid_until:'2030-11-15',annual_ctc:1200000,status:'Draft',offer_text:'Annual compensation and joining terms reviewed by HR.'});
  await reject(save('offers',{...offer,id:undefined}),409);
  await reject(save('offers',{...offer,status:'Pending approval'}),409);
  const completed = await save('interviews',{...interview,status:'Completed',outcome:'Hire'});
  await reject(save('interviews',{...completed,title:'Changed assessment'}),409);
  await save('interviews',{...completed});
  const submitted = await save('offers',{...offer,status:'Pending approval'});
  await reject(save('offers',{...submitted,status:'Approved'},{...actor,original_role:'employee'}),403);
  await reject(save('offers',{...submitted,status:'Approved',annual_ctc:2400000}),409);
  const approvedOffer = await save('offers',{...submitted,status:'Approved'});
  assert.equal(approvedOffer.approved_by,actor.user_id);
  const offered = await save('candidates',{...interviewing,status:'Offered'});
  assert.equal(offered.status,'Offered');
  await reject(save('candidates',{...offered,status:'Hired'}),409);
  await reject(save('offers',{...approvedOffer,status:'Sent'}),409);
  const cancelled = await save('interviews',{...adjacent,status:'Cancelled'});
  await reject(save('interviews',{...cancelled,status:'Scheduled'}),409);
  await save('interviews',{...interviewInput,start_time:'11:00',end_time:'12:00'});
  assert.equal((await talentHandle({db,actor,path:`/api/v1/talent/offers/${offer.id}/audit`,method:'GET',url:new URL('https://test')})).length,3);
  sqlite.exec("CREATE TRIGGER fail_audit BEFORE INSERT ON talent_audit BEGIN SELECT RAISE(ABORT,'audit unavailable'); END;");
  await assert.rejects(save('requisitions',{...input,title:'Rollback check'}),/audit unavailable/);
  assert.equal(sqlite.prepare("SELECT count(*) AS n FROM talent_records WHERE json_extract(payload,'$.title')='Rollback check'").get().n,0);
  await assert.rejects(save('interviews',{...interviewInput,title:'Interview rollback',start_time:'15:00',end_time:'16:00'}),/audit unavailable/);
  assert.equal(sqlite.prepare("SELECT count(*) AS n FROM talent_records WHERE json_extract(payload,'$.title')='Interview rollback'").get().n,0);
  console.log('Recruitment checks passed: transitions, candidate deduplication, interview overlap/adjacency, terminal locks, offer assessments/approval/duplicates, company isolation, revisions and atomic audit rollback.');
} finally { sqlite.close(); }
